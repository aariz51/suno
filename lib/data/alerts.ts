/** Alerts affecting a district, most severe first. */
export function alertsFor(districtId: string): Alert[] {
  return ALERTS.filter((a) => a.districtId === districtId)
    .sort((a, b) => level(b) - level(a));
}

/** The single alert that should own the screen for a district, if any. */
export function topAlert(districtId: string): Alert | null {
  return alertsFor(districtId)[0] ?? null;
}

