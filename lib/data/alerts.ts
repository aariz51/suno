// -----------------------------------------------------------------------------
// ALERTS — modelled on CAP v1.2 (Common Alerting Protocol, OASIS standard)
// -----------------------------------------------------------------------------
// Every alert in this file is SYNTHETIC. Nothing here came from IMD, CWC, INCOIS
// or NDMA's Sachet system, and this prototype is not connected to any of them.
//
// The SHAPE, however, is deliberately real. CAP v1.2 is the format Sachet
// already emits and the format IMD, CWC and INCOIS already publish in. Modelling
// the synthetic data on the true schema is what makes the claim on /how-it-runs
// checkable rather than aspirational: swapping this array for a live CAP feed is
// a parser change, not a redesign. Field names below map 1:1 to CAP elements.
//
//   identifier / sender / sent / status / msgType / scope   → <alert>
//   category / event / urgency / severity / certainty       → <info>
//   effective / onset / expires / instruction               → <info>
//   areaDesc / geocode / polygon                            → <area>
// -----------------------------------------------------------------------------

import type { HazardType, LangCode } from "./districts";

/** CAP <severity>. Mapped to the four-level citizen scale in level(). */
export type CapSeverity = "Extreme" | "Severe" | "Moderate" | "Minor";
/** CAP <urgency>. */
export type CapUrgency = "Immediate" | "Expected" | "Future" | "Past";
/** CAP <certainty>. */
export type CapCertainty = "Observed" | "Likely" | "Possible" | "Unlikely";

/** The citizen-facing scale. Four levels, because five is one more than anyone
 *  can hold under stress and three cannot separate "get ready" from "go now".
 *  Structure follows Japan's five-level system collapsed at the top: their
 *  Levels 4 and 5 are both "evacuate", and the distinction between them has been
 *  shown to cost time. Documented on /how-it-runs. */
export type Level = 1 | 2 | 3 | 4;

export interface Alert {
  /** CAP <identifier>. Format mirrors Sachet's: SENDER.YYYY.NNNN */
  identifier: string;
  /** CAP <sender>. Synthetic sender IDs in the real agencies' namespace shape. */
  sender: string;
  senderName: string;
  /** CAP <sent>, ISO 8601. Relative to app load — see resolveTimes(). */
  sentOffsetMin: number;
  /** CAP <onset> — when impact begins. Minutes from load. Null = already begun. */
  onsetOffsetMin: number | null;
  /** CAP <expires>. Minutes from load. */
  expiresOffsetMin: number;

  status: "Actual" | "Exercise" | "Test";
  msgType: "Alert" | "Update" | "Cancel";
  scope: "Public";

  category: "Met" | "Geo" | "Safety" | "Fire" | "Health";
  event: string;
  hazard: HazardType;
  urgency: CapUrgency;
  severity: CapSeverity;
  certainty: CapCertainty;

  districtId: string;
  areaDesc: string;

  /** CAP <headline>. Kept under 60 chars — it has to survive an SMS and a
   *  lock-screen notification without truncating mid-word. */
  headline: string;
  /** CAP <description>. Written the way the source agency writes: precise,
   *  technical, and not actionable by itself. This is the input to /api/plain. */
  description: string;
  /** CAP <instruction>. The ordered actions. Never generated by a model —
   *  see lib/rules.ts. */
  instruction: string[];
  /** Things NOT to do. The original portal buried these; they are the actions
   *  that actually kill people (driving through water, using lifts). */
  avoid: string[];

  /** CAP <parameter> — the measured quantity, if the hazard has one. This is
   *  the number that makes a warning checkable instead of atmospheric. */
  measure?: { label: string; value: string; threshold: string; trend?: string };

  /** Whether a shelter list is relevant for this alert. */
  shelters: boolean;
}

// -----------------------------------------------------------------------------

export function level(a: Pick<Alert, "severity" | "urgency">): Level {
  if (a.severity === "Extreme" && a.urgency === "Immediate") return 4;
  if (a.severity === "Extreme" || a.severity === "Severe") return 3;
  if (a.severity === "Moderate") return 2;
  return 1;
}

