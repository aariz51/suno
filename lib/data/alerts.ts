// -----------------------------------------------------------------------------
// POPULATION UNDER A WARNING
// -----------------------------------------------------------------------------
// Borrowed from BhimShila (github.com/CyNoGeN1109/bhimshila), which ranks live
// Sachet alerts by how many people are actually underneath each one. It is the
// best idea in the Indian disaster-tooling field right now and it costs us
// almost nothing, because district population is already in the dataset.
//
// The reason it matters: a warning feed sorted by severity alone tells a reader
// that four things are Level 3. It does not tell them that one of those covers
// nine million people and another covers eight thousand. Severity is a property
// of the hazard; exposure is a property of the people. Ranking on severity and
// then on exposure is closer to how a district control room actually triages.
//
// The number here is the district's whole 2011 Census population, which is a
// CEILING, not an estimate of who is in the hazard footprint — a river warning
// does not threaten everyone in the district. It is labelled that way on screen
// rather than being presented as a casualty projection.
// -----------------------------------------------------------------------------

import { DISTRICT_BY_ID } from "./districts";

export function populationUnder(a: Alert): number {
  return DISTRICT_BY_ID[a.districtId]?.pop ?? 0;
}

/** Severity first, then exposure. Never exposure first: a Level 4 over a small
 *  district still outranks a Level 2 over a city, because the level is a
 *  statement about what is about to happen to the people who are there. */
export function rankAlerts(list: Alert[]): Alert[] {
  return [...list].sort((x, y) => {
    const lv = level(y) - level(x);
    if (lv !== 0) return lv;
    return populationUnder(y) - populationUnder(x);
  });
}

/** Total population under every alert at or above a level. Used on /how-it-runs
 *  to make the scale of the feed concrete. */
export function populationAtOrAbove(lv: Level): number {
  return ALERTS.filter((a) => level(a) >= lv).reduce((n, a) => n + populationUnder(a), 0);
}

/** "9.4 million" / "8,100" — a number a person can hold, not 9429408. */
export function formatPeople(n: number): string {
  if (n >= 10_000_000) return `${(n / 10_000_000).toFixed(1)} crore`;
  if (n >= 100_000) return `${(n / 100_000).toFixed(1)} lakh`;
  return n.toLocaleString("en-IN");
}
